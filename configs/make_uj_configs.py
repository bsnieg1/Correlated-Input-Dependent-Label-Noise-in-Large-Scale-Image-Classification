"""Generates the Multispecies Campus UJ configs: label source x method.

    python configs/make_uj_configs.py

    uj_model_<method>.yaml   step 1: train on SpeciesNet labels, test on expert labels
    uj_expert_<method>.yaml  step 2: train on expert labels, test on expert labels
Paths point to the local data on D: (see CLAUDE.md); hub_dir keeps the ImageNet weights off C:.
ResNet-18, not ResNet-50: on the 6 GB GTX 1060, ResNet-50 at 224x416 ran ~7x slower (memory-bound).
"""
from pathlib import Path

import yaml

HERE = Path(__file__).parent
ROOT = "D:/inzynier_temp"
DATA = {"name": "uj", "num_classes": 17, "labels_dir": f"{ROOT}/LL_Dane_studenci copy",
        "images_dir": f"{ROOT}/zenodo_1024", "cache_dir": f"{ROOT}/cache",
        "taxonomy": f"{ROOT}/LL_Dane_studenci copy/ROZNE_MATERIALY/klasy_gatunki_zwierzat_z_modelu_przy_uzepelnianiu.txt",
        "size": [240, 448], "crop": [224, 416], "split_seed": 0, "n_folds": 7, "num_pairs": 5}
MODEL = {"name": "resnet18", "pretrained": True, "hub_dir": f"{ROOT}/torch_hub"}
TRAIN = {"epochs": 15, "batch_size": 32, "lr": 0.01, "momentum": 0.9, "weight_decay": 1.0e-4, "eval_batch_size": 64}
METHODS = {
    "ce": ({"name": "linear"}, {}),
    "ls": ({"name": "linear"}, {"label_smoothing": 0.1}),
    "het_diag": ({"name": "het_diag", "temperature": 1.0, "num_samples": 1000}, {}),
    "het": ({"name": "het", "num_factors": 5, "temperature": 1.0, "num_samples": 1000}, {}),
}
STEPS = {"model": "step 1: SpeciesNet labels", "expert": "step 2: expert labels"}


def main():
    n = 0
    for labels, title in STEPS.items():
        for method, (head, extra) in METHODS.items():
            name = f"uj_{labels}_{method}"
            cfg = {"experiment": name, "method": method, "data": {**DATA, "train_labels": labels},
                   "model": dict(MODEL), "head": dict(head), "train": {**TRAIN, **extra}}
            (HERE / f"{name}.yaml").write_text(f"# Multispecies Campus UJ, {title}, method {method}. "
                                               f"Generated by make_uj_configs.py.\n" + yaml.safe_dump(cfg, sort_keys=False))
            n += 1
    print(f"{n} configs written")


if __name__ == "__main__":
    main()
