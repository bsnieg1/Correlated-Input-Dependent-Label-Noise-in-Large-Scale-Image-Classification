"""Generates all MNIST experiment configs.

    python configs/make_mnist_configs.py

Main grid: scenarios S0-S3 x methods CE / LS / HET-diag / HET  ->  mnist_<scenario>_<method>.yaml
Ablation on S1-30%: R x tau for HET                                ->  mnist_abl_r<R>_t<tau>.yaml
(R = 3, tau = 1 is the main HET config mnist_s1_p30_het and is not duplicated.)
"""
from pathlib import Path

import yaml

HERE = Path(__file__).parent
PAIRS = [[1, 7], [4, 9], [3, 8]]

DATA = {"name": "mnist", "root": "data", "num_classes": 10, "val_fraction": 0.1, "split_seed": 0}
MODEL = {"name": "small_cnn", "in_channels": 1, "feature_dim": 128}
TRAIN = {"epochs": 15, "batch_size": 128, "lr": 0.05, "momentum": 0.9, "weight_decay": 5.0e-4}

SCENARIOS = {
    "s0": ("S0: clean labels", None),
    "s1_p10": ("S1: class-dependent pair noise 10%", {"type": "pair", "rate": 0.10, "pairs": PAIRS}),
    "s1_p30": ("S1: class-dependent pair noise 30%", {"type": "pair", "rate": 0.30, "pairs": PAIRS}),
    "s1_p45": ("S1: class-dependent pair noise 45%", {"type": "pair", "rate": 0.45, "pairs": PAIRS}),
    "s2_p30": ("S2: image-dependent pair noise, mean 30%, P(flip) ~ p_aux(partner | x)",
               {"type": "instance", "rate": 0.30, "pairs": PAIRS, "max_prob": 0.45,
                "aux_temperature": 4.0, "aux_epochs": 3, "aux_folds": 2}),
    "s3_p30": ("S3: negative control, 30% symmetric noise", {"type": "symmetric", "rate": 0.30}),
}

HET = {"name": "het", "num_factors": 3, "temperature": 1.0, "num_samples": 1000}
METHODS = {  # method -> (head, extra train options)
    "ce": ({"name": "linear"}, {}),
    "ls": ({"name": "linear"}, {"label_smoothing": 0.1}),
    "het_diag": ({"name": "het_diag", "temperature": 1.0, "num_samples": 1000}, {}),
    "het": (HET, {}),
}

ABLATION_R = [1, 2, 3, 5]
ABLATION_TAU = [0.5, 1.0, 2.0]


def make(experiment, method, noise, head, train_extra):
    data = dict(DATA)
    if noise is not None:
        data["noise"] = {**noise, "seed": 0}
    return {"experiment": experiment, "method": method, "data": data, "model": dict(MODEL),
            "head": dict(head), "train": {**TRAIN, **train_extra}}


def write(name, title, cfg):
    path = HERE / f"{name}.yaml"
    path.write_text(f"# {title}. Generated by make_mnist_configs.py.\n" + yaml.safe_dump(cfg, sort_keys=False))
    return path


def main():
    paths = []
    for scenario, (title, noise) in SCENARIOS.items():
        for method, (head, extra) in METHODS.items():
            name = f"mnist_{scenario}_{method}"
            paths.append(write(name, f"{title}; method {method}", make(name, method, noise, head, extra)))
    noise = SCENARIOS["s1_p30"][1]
    for R in ABLATION_R:
        for tau in ABLATION_TAU:
            if (R, tau) == (HET["num_factors"], HET["temperature"]):
                continue
            name = f"mnist_abl_r{R}_t{tau:g}"
            head = {**HET, "num_factors": R, "temperature": tau}
            paths.append(write(name, f"Ablation on S1-30%: R = {R}, tau = {tau:g}", make(name, "het", noise, head, {})))
    print(f"{len(paths)} configs written")


if __name__ == "__main__":
    main()
